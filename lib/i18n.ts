export type MessageKey = keyof typeof en;
export const messages = { en, "zh-CN": zhCN, "zh-TW": zhTW, ja };

export function resolveLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const tag = language.toLowerCase();
    if (tag === "zh" || tag.startsWith("zh-")) {
      if (tag.includes("hans")) return "zh-CN";
      return /(?:hant|tw|hk|mo)/.test(tag) ? "zh-TW" : "zh-CN";
    }
    if (tag === "ja" || tag.startsWith("ja-")) return "ja";
    if (tag === "en" || tag.startsWith("en-")) return "en";
  }
  return "en";
}

export function parseAcceptLanguage(header: string): string[] {
  return header.split(",").map((entry) => {
    const [tag, ...parameters] = entry.trim().split(";");
    const quality = parameters.find((parameter) => parameter.trim().startsWith("q="));
    return { tag, weight: quality ? Number(quality.trim().slice(2)) : 1 };
  }).filter(({ weight }) => weight > 0)
    .sort((a, b) => b.weight - a.weight).map(({ tag }) => tag);
}

export function languagePreference(value?: string): LanguagePreference {
  return locales.find((locale) => locale === value) ?? "system";
}

export function themePreference(value?: string): ThemePreference {
  return value === "light" || value === "dark" ? value : "system";
}
